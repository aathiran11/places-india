export function slugifyStateName(name: string): string {
  return name
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

export function getStateTheme(stateName: string | undefined): StateTheme {
  if (!stateName) return DEFAULT_THEME;
  return STATE_THEMES[stateName] || DEFAULT_THEME;
}
